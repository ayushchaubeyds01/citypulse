import CivicEvent from "../models/civicEvent.model.js";

export const createTrafficEvent = async (req, res) => {
  try {
    const trafficEvent = await CivicEvent.create({
      source: "traffic",
      eventType: "traffic_update",
      title: "Traffic Update",
      description: "Synthetic traffic data generated by CityPulse.",
      location: {
        latitude: 26.9124,
        longitude: 75.7873,
        address: "Jaipur",
      },
      severity: "low",
      status: "active",
      value: 35,
      unit: "km/h",
      timestamp: new Date(),
    });

    return res.status(201).json({
      success: true,
      message: "Traffic event created successfully",
      data: trafficEvent,
    });
  } catch (error) {
    console.error("Traffic event creation failed:", error);

    return res.status(500).json({
      success: false,
      message: "Failed to create traffic event",
      error: error.message,
    });
  }
};